"""Shared fixtures for the bin/spud test suite.

Every database, render target and settings file a test touches lives under a
tempfile directory: a Home is a temporary SPUD_HOME with its own copy of
spud.config.json. Nothing here writes into the repository.
"""

import atexit
import importlib.machinery
import importlib.util
import json
import os
import shutil
import sqlite3
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

# The suite must leave no bytecode in the repo: bin/spud is loaded as a module
# by the parser tests, and `-I -S` does not read PYTHONDONTWRITEBYTECODE.  The
# first test module unittest imports is compiled before this line runs, so the
# cache directories are also removed when the interpreter exits.
sys.dont_write_bytecode = True

REPO = Path(__file__).resolve().parent.parent


def _remove_bytecode():
    for cache in (REPO / "bin" / "__pycache__", REPO / "tests" / "__pycache__"):
        shutil.rmtree(cache, ignore_errors=True)


atexit.register(_remove_bytecode)

SPUD = REPO / "bin" / "spud"
CONFIG = REPO / "spud.config.json"
MARKER = "<!-- generated by spud from .spud/ledger.db; edit with the spud CLI -->"

# Exit codes the CLI promises.
EXIT_OK = 0
EXIT_ERROR = 1
EXIT_USAGE = 2
EXIT_OWNERSHIP = 3
EXIT_LIMIT = 4
EXIT_TRANSITION = 5
EXIT_CONFLICT = 6


def real_config():
    with open(CONFIG, encoding="utf-8") as f:
        return json.load(f)


def load_spud_module():
    """Import bin/spud as a module (it has no .py suffix) for parser unit tests."""
    loader = importlib.machinery.SourceFileLoader("spud", str(SPUD))
    spec = importlib.util.spec_from_loader("spud", loader)
    module = importlib.util.module_from_spec(spec)
    loader.exec_module(module)
    return module


class Home:
    """A temporary SPUD_HOME with a config file; runs the CLI against it."""

    def __init__(self, config=None):
        self._tmp = tempfile.TemporaryDirectory(prefix="spud-test-")
        self.path = Path(self._tmp.name).resolve()
        self.config = config if config is not None else real_config()
        with open(self.path / "spud.config.json", "w", encoding="utf-8") as f:
            json.dump(self.config, f, indent=2)
        self.env = dict(os.environ)
        self.env["SPUD_HOME"] = str(self.path)
        self.db = self.path / ".spud" / "ledger.db"

    def cleanup(self):
        self._tmp.cleanup()

    def run(self, *args, check=True, actor=None, stdin=None):
        cmd = [sys.executable, "-I", "-S", str(SPUD)]
        if actor is not None:
            cmd += ["--as", actor]
        cmd += [str(a) for a in args]
        proc = subprocess.run(cmd, capture_output=True, text=True, env=self.env, input=stdin)
        if check and proc.returncode != 0:
            raise AssertionError(
                "spud %s exited %d\nstdout: %s\nstderr: %s"
                % (" ".join(str(a) for a in args), proc.returncode, proc.stdout, proc.stderr)
            )
        return proc

    def json(self, *args, actor=None, check=True, stdin=None):
        proc = self.run("--json", *args, actor=actor, check=check, stdin=stdin)
        try:
            return json.loads(proc.stdout)
        except json.JSONDecodeError as e:
            raise AssertionError("not JSON: %r (stderr %r)" % (proc.stdout, proc.stderr)) from e

    def init(self):
        return self.json("init")

    def connect(self):
        con = sqlite3.connect(self.db, timeout=5)
        con.row_factory = sqlite3.Row
        return con

    def scalar(self, sql, *params):
        con = self.connect()
        try:
            row = con.execute(sql, params).fetchone()
            return None if row is None else row[0]
        finally:
            con.close()

    def rows(self, sql, *params):
        con = self.connect()
        try:
            return [dict(r) for r in con.execute(sql, params).fetchall()]
        finally:
            con.close()

    def write_settings(self, data):
        p = self.path / ".claude" / "settings.json"
        p.parent.mkdir(parents=True, exist_ok=True)
        with open(p, "w", encoding="utf-8") as f:
            json.dump(data, f, indent=2)
            f.write("\n")
        return p


class SpudTestCase(unittest.TestCase):
    """A test case with a fresh initialised Home per test."""

    config = None

    def setUp(self):
        self.home = Home(config=self.config)
        self.addCleanup(self.home.cleanup)
        self.home.init()

    # Small builders used across files.
    def new_ticket(self, title="A ticket", **kw):
        args = ["ticket", "new", "--title", title]
        for k, v in kw.items():
            if isinstance(v, (list, tuple)):
                for item in v:
                    args += ["--" + k.replace("_", "-"), item]
            else:
                args += ["--" + k.replace("_", "-"), v]
        return self.home.json(*args, actor="spud")["ticket"]

    def new_member(self, ticket, actor="spud", persona="scout", model="haiku", **kw):
        kw.setdefault("brief", "Do the thing.")
        args = ["member", "new", "--ticket", ticket, "--persona", persona, "--model", model]
        for k, v in kw.items():
            if isinstance(v, (list, tuple)):
                for item in v:
                    args += ["--" + k.replace("_", "-"), item]
            else:
                args += ["--" + k.replace("_", "-"), v]
        return self.home.json(*args, actor=actor)["member"]


def normalize_markdown(text):
    """The acceptance test's allowed differences: marker line, trailing
    whitespace, runs of blank lines (and blank lines at either end)."""
    out = []
    for line in text.splitlines():
        if line.strip() == MARKER:
            continue
        line = line.rstrip()
        if line == "" and out and out[-1] == "":
            continue
        out.append(line)
    while out and out[0] == "":
        out.pop(0)
    while out and out[-1] == "":
        out.pop()
    return "\n".join(out) + "\n"
