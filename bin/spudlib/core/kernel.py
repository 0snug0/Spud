class Result:
    """A command's answer.  `raw` (hooks) is printed verbatim on stdout with the given
    exit code, whatever --json says; everything else prints `text` or `data` as JSON, then
    `stderr` as a `spud:` line, and exits with `exit_code` (member resum: 1 with its table)."""

    def __init__(self, data, text="", raw=None, exit_code=EXIT_OK, stderr=""):
        self.data = data
        self.text = text
        self.raw = raw
        self.exit_code = exit_code
        self.stderr = stderr


def table(rows, columns):
    """A plain text table: columns is [(header, key)]."""
    if not rows:
        return "(none)"
    widths = [max(len(h), *(len(str(r.get(k, "") if r.get(k) is not None else "")) for r in rows)) for h, k in columns]
    lines = ["  ".join(h.ljust(w) for (h, _), w in zip(columns, widths)).rstrip()]
    for r in rows:
        lines.append("  ".join(str(r.get(k, "") if r.get(k) is not None else "").ljust(w) for (_, k), w in zip(columns, widths)).rstrip())
    return "\n".join(lines)
