def now():
    """ISO 8601 with seconds and the local offset; the only clock the ledger has."""
    return datetime.now().astimezone().isoformat(timespec="seconds")


def fm_date(stamp):
    return "" if not stamp else stamp[:10]


def fm_minute(stamp):
    return "" if not stamp else stamp[:16]


def seconds_since(stamp, now=None):
    """Seconds between an ISO stamp the ledger wrote and now; None when the stamp cannot be read or compared.  Moved down
    from commands/prcmds: a pull request's last read and the vault's lag ask the same question, and the lag is
    asked on the hook path, which no command module may serve."""
    try:
        return ((datetime.now().astimezone() if now is None else now) - datetime.fromisoformat(stamp)).total_seconds()
    except (TypeError, ValueError):
        return None


def ago_text(seconds):
    """`40s ago`, `4m ago`, `3h ago`, `2d ago`, for how long ago a check was made or an event went unrendered."""
    if seconds is None:
        return "at a time that cannot be read"
    if seconds < 1:
        return "just now"
    if seconds < 90:
        return "%ds ago" % int(seconds)
    if seconds < 5400:
        return "%dm ago" % round(seconds / 60)
    if seconds < 172800:
        return "%dh ago" % round(seconds / 3600)
    return "%dd ago" % round(seconds / 86400)


def sha256_bytes(data):
    return lazy.hashlib.sha256(data).hexdigest()


def write_whole(path, content):
    """Write via a temp file in the same directory and rename, so no reader sees a half-written note."""
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = lazy.tempfile.mkstemp(prefix=".spud-", suffix=".tmp", dir=str(path.parent))
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as f:
            f.write(content)
        os.replace(tmp, path)
    except BaseException:
        with contextlib.suppress(OSError):
            os.unlink(tmp)
        raise


def write_bytes(path, data):
    """`write_whole` for bytes: a temporary file in the same directory, renamed into place, so a reader -- and Obsidian
    is a reader -- never sees half a plugin.  Moved here from `commands/vaultlock` when `state/backup` came
    to need it for the copy every command keeps before it overwrites a tool-owned file."""
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.parent / (".spud-" + path.name + ".tmp")
    try:
        tmp.write_bytes(data)
        os.replace(tmp, path)
    except BaseException:
        if tmp.exists():
            tmp.unlink()
        raise


